"""Generate the Databricks export notebook and package its output into one HTML file."""
import argparse
import importlib.util
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "dashboards/gilded_ace.lvdash.json"
NOTEBOOK = ROOT / "databricks/export/twin.py"
EXPORT = ROOT / "embed/.gold-export.json"
OUTPUT = ROOT / "embed/public/index.html"
MACHINE = """SELECT d.gaming_date,d.machine_id,d.zone_name,d.bank_name,d.x_m,d.y_m,d.config_id,d.manufacturer,d.downtime_hours,d.zone_id,
 d.coin_in_usd,d.house_win_usd,d.theo_usd,d.leak_usd,d.location_opportunity_usd,
 d.luck_residual_usd,d.luck_variance_usd2,d.potential_theo_usd,d.location_usd,
 d.lineup_usd,d.machine_specific_usd,d.available_hours,v.gm_rank,v.verdict_chip,
 v.adjusted_rank,v.last_bank_name
 FROM workspace.royale.gold_machine_day d JOIN workspace.royale.gold_machine_verdict v USING (machine_id)"""
TIMELINE = """SELECT machine_id,gaming_date,
 SORT_ARRAY(COLLECT_LIST(NAMED_STRUCT('h', gaming_hour, 'utc', hour_start_utc,
  'a', ROUND(available_hours,4), 'd', ROUND(downtime_hours,4)))) AS hours
 FROM workspace.royale.gold_machine_hour_leak
 WHERE downtime_hours > 0 OR ABS(available_hours - 1) > 0.00001
 GROUP BY machine_id,gaming_date"""
KPI_FIELDS = ("SUM(coin_in_usd) AS coin", "SUM(theo_usd) AS theo",
              "SUM(house_win_usd) AS win", "SUM(leak_usd) AS leak",
              "SUM(luck_usd) AS luck", "SUM(luck_variance_usd2) AS variance",
              "SUM(health_potential_usd) AS potential",
              "SUM(comp_cost_usd) AS comp", "SUM(tracked_theo_usd) AS tracked")


def queries():
    spec = importlib.util.spec_from_file_location("dashboard", ROOT / "dashboards/build_dashboard.py")
    dashboard = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(dashboard)
    result = dashboard.datasets()
    result["machine"] = MACHINE
    result["demand"] = """SELECT d.gaming_date,d.coin_in_usd,f.forecast_usd,f.split
        FROM workspace.royale.gold_demand_context_day d
        JOIN workspace.royale.gold_forecast_day f USING (gaming_date)"""
    result["fault"] = """SELECT machine_id,gaming_date,gaming_hour,wait_seconds,work_seconds
        FROM workspace.royale.gold_downtime_ticket WHERE event_type='fault_repair'"""
    result["segments"] = "SELECT * FROM workspace.royale_export.gold_guest_group_day"
    result.update({key: f"SELECT * FROM workspace.royale.{view}" for key, view in {
        "lasting_gap": "gold_back_forty_lasting_gap",
        "high_limit_test": "gold_high_limit_visit_test",
        "high_limit_day": "gold_high_limit_visit_day",
        "comp_control_week": "gold_comp_control_week",
        "comp_control_pretrend": "gold_comp_control_pretrend",
    }.items()})
    result["demand_bridge"] = "SELECT * FROM workspace.royale_export.gold_demand_bridge_day"
    result["export_metadata"] = """SELECT CAST(current_date() AS STRING) AS exported_on
        FROM workspace.royale.gold_kpi_header LIMIT 1"""
    result["downtime"] = """SELECT gaming_date,gaming_hour,zone_id,manufacturer,
        downtime_hours,lost_theo_usd FROM workspace.royale.gold_downtime_exposure_day_hour
        WHERE downtime_hours > 0 OR lost_theo_usd <> 0"""
    result["comp_days"] = """SELECT k.gaming_date,k.comp_cost_usd,k.tracked_theo_usd,k.theo_usd,
        COALESCE(r.points,0) AS points,COALESCE(r.face_usd,0) AS face_usd
        FROM workspace.royale.gold_kpi_header k LEFT JOIN
        (SELECT gaming_date,SUM(points) AS points,SUM(face_usd) AS face_usd
         FROM workspace.royale.gold_comp_tier_day GROUP BY gaming_date) r USING (gaming_date)"""
    result["timeline"] = TIMELINE
    result["kpi_expected"] = " UNION ALL ".join(
        f"""SELECT '{start}' AS start, '{end}' AS end,
        CAST(ROUND(CAST(SUM(theo_usd) AS DOUBLE)/SUM(health_potential_usd),8) AS DECIMAL(22,8)) AS health,
        CAST(ROUND(SUM(coin_in_usd),2) AS DECIMAL(22,2)) AS coin,
        CAST(ROUND(CAST(SUM(house_win_usd) AS DOUBLE)/SUM(coin_in_usd),8) AS DECIMAL(22,8)) AS hold,
        CAST(ROUND(CAST(SUM(theo_usd) AS DOUBLE)/SUM(coin_in_usd),8) AS DECIMAL(22,8)) AS theo_hold,
        CAST(ROUND(SUM(luck_usd),2) AS DECIMAL(22,2)) AS luck,
        CAST(ROUND(SUM(leak_usd),2) AS DECIMAL(22,2)) AS leak,
        CAST(ROUND(CAST(SUM(comp_cost_usd) AS DOUBLE)/SUM(tracked_theo_usd),8) AS DECIMAL(22,8)) AS comp_kpi,
        CAST(ROUND(SUM(luck_usd)/SQRT(SUM(luck_variance_usd2)),8) AS DECIMAL(22,8)) AS sigma_kpi,
        (SELECT MAX(kept_usd) FROM workspace.royale.gold_cage_slip) AS cash_kept
        FROM workspace.royale.gold_kpi_header WHERE gaming_date BETWEEN '{start}' AND '{end}'"""
        for start, end in [("2025-01-01", "2025-06-30"), ("2025-04-01", "2025-06-30"), ("2025-03-03", "2025-04-07")]
    )
    return result


def notebook():
    NOTEBOOK.write_text("# Databricks notebook source\n# Generated by twin/build.py notebook.\n"
                        "QUERIES = " + repr(queries()) + "\n" +
                        (ROOT / "twin/export_notebook.py").read_text())


def build():
    source = json.loads(EXPORT.read_text())
    if set(source) != set(queries()) or any(not dataset["rows"] for dataset in source.values()):
        raise SystemExit("Incomplete Databricks export")
    forbidden = {"visitor_volume", "visitor_yoy_ratio", "player_id", "_rescued_data"}
    if any(forbidden.intersection(dataset["columns"]) for dataset in source.values()):
        raise SystemExit("Export includes fields outside the public snapshot contract; rerun the export job.")
    pages = [page for page in json.loads(SPEC.read_text())["pages"] if page["pageType"] != "PAGE_TYPE_GLOBAL_FILTERS"]
    date, = source["export_metadata"]["rows"][0]
    source.pop("kpi_expected")
    payload = json.dumps({"datasets": source, "pages": pages}, ensure_ascii=False, separators=(",", ":")).replace(chr(8212), ". ").encode()

    html = (ROOT / "twin/index.html").read_text()
    for marker, value in [("/* STYLE */", (ROOT / "twin/style.css").read_text()),
                          ("/* APP */", (ROOT / "twin/copy.js").read_text() + "\n" + (ROOT / "twin/app.js").read_text())]:
        html = html.replace(marker, value)
    html = html.replace("__EXPORT_DATE__", date).replace(chr(8212), ". ")
    assert chr(8212) not in html
    OUTPUT.parent.mkdir(exist_ok=True)
    OUTPUT.write_text(html)
    (OUTPUT.parent / "gold.json").write_bytes(payload)
    for asset in ("live.html", "style.css", "dashboard.mjs"):
        if asset == "live.html":
            (OUTPUT.parent / asset).write_text((ROOT / "embed" / asset).read_text().replace("__EXPORT_DATE__", date))
        else:
            shutil.copyfile(ROOT / "embed" / asset, OUTPUT.parent / asset)
    for file in OUTPUT.parent.iterdir():
        if file.suffix in {".html", ".json", ".css", ".mjs"}:
            assert chr(8212) not in file.read_text(), f"Em dash found in {file.name}"


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("step", choices=["notebook", "build"])
    globals()[parser.parse_args().step]()
